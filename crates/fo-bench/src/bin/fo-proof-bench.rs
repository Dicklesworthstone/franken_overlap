use std::collections::BTreeSet;
use std::error::Error;
use std::path::PathBuf;

use clap::Parser;
use fo_corpus::atomic_write;
use scenario_benchmark::{
    ScenarioBenchmarkOptions, ScenarioBenchmarkReport, read_queries, run_scenario_benchmark,
    write_score_rows,
};

type CliResult<T> = Result<T, Box<dyn Error + Send + Sync>>;

#[derive(Debug, Parser)]
#[command(
    name = "fo-proof-bench",
    version,
    about = "Benchmark curated real-corpus scenarios across nested corpus sizes and retrieval methods"
)]
struct Cli {
    /// Searchable fo-corpus root, normally showcase/<provider>/sections.
    corpus_root: PathBuf,
    /// Scenario query JSONL generated by fo-showcase or manually adjudicated.
    queries: PathBuf,
    #[arg(short, long)]
    output: PathBuf,
    #[arg(long)]
    scores_output: Option<PathBuf>,
    /// Repeat to request explicit nested corpus sizes.
    #[arg(long = "corpus-size")]
    corpus_sizes: Vec<usize>,
    #[arg(long, default_value_t = 250)]
    maximum_documents: usize,
    #[arg(long, default_value_t = usize::MAX)]
    maximum_queries: usize,
    /// Repeat to benchmark only selected scenario profiles.
    #[arg(long = "profile")]
    profiles: Vec<String>,
    #[arg(long, default_value_t = 1)]
    warmup_runs: usize,
    #[arg(long, default_value_t = 3)]
    measurement_repetitions: usize,
    #[arg(long, default_value_t = 5)]
    qgram_size: usize,
    #[arg(long, default_value_t = 128 * 1024 * 1024)]
    maximum_document_bytes: u64,
    #[arg(long, default_value_t = 2_000_000_000)]
    maximum_exhaustive_cells_per_query: u64,
    #[arg(long, default_value_t = 20_000_000_000)]
    maximum_exhaustive_cells_per_scale: u64,
    #[arg(long, default_value_t = 0x70_72_6f_6f_66_2d_62_65)]
    seed: u64,
    /// Directory for serialized indexes. Temporary indexes are used when omitted.
    #[arg(long)]
    index_root: Option<PathBuf>,
    #[arg(long)]
    retain_indexes: bool,
    #[arg(long)]
    json: bool,
}

fn main() {
    if let Err(error) = run() {
        eprintln!("fo-proof-bench: {error}");
        std::process::exit(1);
    }
}

fn run() -> CliResult<()> {
    let command = Cli::parse();
    let queries = read_queries(&command.queries)?;
    let _relation_group_count = queries
        .iter()
        .map(|query| query.relation_key.as_str())
        .filter(|relation| !relation.is_empty())
        .collect::<BTreeSet<_>>()
        .len();
    let options = ScenarioBenchmarkOptions {
        requested_corpus_sizes: command.corpus_sizes,
        maximum_documents: command.maximum_documents,
        maximum_queries: command.maximum_queries,
        profiles: command.profiles.into_iter().collect::<BTreeSet<_>>(),
        warmup_runs: command.warmup_runs,
        measurement_repetitions: command.measurement_repetitions,
        qgram_size: command.qgram_size,
        maximum_document_bytes: command.maximum_document_bytes,
        maximum_exhaustive_cells_per_query: command.maximum_exhaustive_cells_per_query,
        maximum_exhaustive_cells_per_scale: command.maximum_exhaustive_cells_per_scale,
        seed: command.seed,
        index_root: command.index_root,
        retain_indexes: command.retain_indexes,
    };
    let (report, rows) =
        run_scenario_benchmark(&command.corpus_root, &command.queries, queries, &options)?;
    atomic_write(&command.output, &serde_json::to_vec_pretty(&report)?)?;
    if let Some(path) = &command.scores_output {
        write_score_rows(path, &rows)?;
    }
    if command.json {
        println!("{}", serde_json::to_string_pretty(&report)?);
    } else {
        print_report(&report, &command.output, command.scores_output.as_ref());
    }
    Ok(())
}

fn print_report(
    report: &ScenarioBenchmarkReport,
    output: &std::path::Path,
    scores_output: Option<&PathBuf>,
) {
    println!("Corpus:                 {}", report.corpus_id);
    println!("Available documents:    {}", report.available_documents);
    println!(
        "Required positives:     {}",
        report.required_positive_documents
    );
    println!("Queries:                {}", report.queries);
    println!("Profiles:               {}", report.profiles.join(", "));
    println!(
        "Evaluated sizes:        {:?}",
        report.evaluated_corpus_sizes
    );
    if !report.skipped_corpus_sizes.is_empty() {
        println!("Skipped sizes:          {:?}", report.skipped_corpus_sizes);
    }
    println!("Report:                 {}", output.display());
    if let Some(path) = scores_output {
        println!("Pair scores:            {}", path.display());
    }
    for scale in &report.scales {
        println!();
        println!("=== {} documents ===", scale.corpus_size);
        println!(
            "build={:.3}ms serialize={:.3}ms load={:.3}ms index={} bytes",
            scale.build.build_ms,
            scale.build.serialization_ms,
            scale.build.cold_load_ms,
            scale.build.index_bytes
        );
        println!(
            "exhaustive: complete={} queries={}/{} cells={}",
            scale.exhaustive.complete,
            scale.exhaustive.complete_queries,
            scale.exhaustive.complete_queries + scale.exhaustive.partial_queries,
            scale.exhaustive.cells
        );
        for method in &scale.methods {
            let quality = method
                .quality
                .as_ref()
                .map(|quality| {
                    format!(
                        "micro={:.4} macro={:.4} r@1={:.4}",
                        quality.micro.average_precision,
                        quality.macro_average_precision,
                        quality
                            .recall_at_k
                            .iter()
                            .find(|metric| metric.k == 1)
                            .map_or(0.0, |metric| metric.value)
                    )
                })
                .unwrap_or_else(|| "quality=n/a".to_owned());
            let span = method.span.as_ref().map_or_else(String::new, |span| {
                format!(
                    " span_iou={:.4} span_found={}/{}",
                    span.mean_iou, span.predicted_queries, span.eligible_queries
                )
            });
            println!(
                "{:<34} p95={:>9.3}ms qps={:>10.2} {}{}",
                method.name,
                method.timing.repeat_p95_ms,
                method.timing.operations_per_second,
                quality,
                span
            );
        }
    }
}
